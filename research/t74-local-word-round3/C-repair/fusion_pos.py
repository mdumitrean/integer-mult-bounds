"""Position-class completion of the toolkit's read-fusion family (fusion.py).

For each fusion triple (target t reads A at iA and H at iH, q = a/h dyadic, t untouched between the reads), the toolkit
tries donation positions {iH, lastwrite(H)+1, iA+1} and restores {after iH, before H's next read/scale, early tails, prepend}.
The frame model sees only the order of events on each register chain, so a donation (H += qA) or a B restore (H -= qA)
placed anywhere between two consecutive events of A or H gives the same chains.  This module enumerates one representative
per event class for the donation and for the B restore, under fusion.py's structural preconditions (A holds the value t read
from the donation to the restore; no other reader or scale of H inside the donation window), and returns the candidates
NOT already generated by fusion.candidates.  Tail and prepend restores are taken from fusion.candidates unchanged."""
import collections, json, sys
from fractions import Fraction as Q
def gen(w, G):
    I = G.index(w); B = I['B']; nB = len(B); reads = G.data_reads(w, I)
    base = {json.dumps(c['ed'], sort_keys=True) for c in G.candidates(w, I)}
    def events(r): return sorted(set(I['W'][r]) | set(I['RD'][r]) | set(I['SC'][r]))
    out = []; seen = set()
    for t, rs in reads.items():
        for (iA, A, a) in rs:
            for (iH, H, h) in rs:
                if A == H or iA == iH or A == t or H == t: continue
                lo_t, hi_t = min(iA, iH), max(iA, iH)
                if G.any_in(I['RD'][t] + I['SC'][t], lo_t, hi_t + 1): continue
                q = a / h
                if not G.dyadic(q): continue
                evA, evH = events(A), events(H); ev = sorted(set(evA) | set(evH))
                # donation positions p (insert before base index p), p <= iH; one representative per gap between events
                cand_p = sorted({0} | {e + 1 for e in ev if e + 1 <= iH} | {iH})
                otherH = [x for x in I['RD'][H] + I['SC'][H] if x != iH]
                for p in cand_p:
                    if p > iH: continue
                    lo, hi = (p, iA) if p <= iA else (iA + 1, p)
                    if G.any_in(I['W'][A], lo, hi): continue
                    if G.any_in(otherH, p, iH): continue
                    if G.any_in(I['W'][H], p, iH) and False: pass
                    nxtH = min([x for x in otherH if x > iH], default=nB)
                    cand_r = sorted({iH + 1} | {e + 1 for e in ev if iH + 1 <= e + 1 <= nxtH} | {nxtH})
                    for rpos in cand_r:
                        if rpos > nB or rpos <= iH: continue
                        if G.any_in(I['W'][A], p, rpos): continue
                        if G.any_in(otherH, p, rpos): continue
                        g = ['add', H, A, q.numerator, q.denominator, []]; gr = ['add', H, A, -q.numerator, q.denominator, []]
                        ed = dict(delete=[iA], insert=[(p, g), (rpos, gr)], tail=[], prepend=[])
                        k = json.dumps(ed, sort_keys=True)
                        if k in base or k in seen: continue
                        seen.add(k); out.append(dict(t=t, A=A, H=H, iA=iA, iH=iH, p=p, rest='Bpos@%d' % rpos, ed=ed))
    return out
if __name__ == '__main__':
    sys.path.insert(0, sys.argv[1]); import harness as Hm, fusion as G
    w = Hm.load(sys.argv[2]); cs = gen(w, G)
    print('new position-class candidates:', len(cs), 'triples', len({(c['t'], c['A'], c['H']) for c in cs}))
